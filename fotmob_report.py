def extract_match_id(url: str) -> str:
    """
    FotMob match URLs look like:
        https://www.fotmob.com/matches/<slug>/<shortcode>#<matchId>
    The numeric matchId after the '#' is what the API keys off of.
    """
    m = re.search(r'#(\d+)', url)
    if m:
        return m.group(1)
    m = re.search(r'/(\d+)(?:[/?#]|$)', url)
    if m:
        return m.group(1)
    raise ValueError(
        f"Couldn't find a numeric matchId in URL: {url!r}. "
        "Expected something like '...#4813652' at the end."
    )


def _find_next_data_json(html: str):
    """Look for Next.js's embedded page-data script tag, if present."""
    soup = BeautifulSoup(html, 'html.parser')
    tag = soup.find('script', id='__NEXT_DATA__')
    if tag and tag.string:
        try:
            return json.loads(tag.string)
        except json.JSONDecodeError:
            return None
    return None


def _search_for_key(obj, target_keys, max_depth=25):
    """
    Recursively search a nested dict/list for the first value whose key
    is in `target_keys`. Next.js nests the real API payload under a few
    layers of pageProps/dehydratedState/etc. that can shift between
    FotMob deploys - searching by key name is more resilient than
    hard-coding one exact path.
    """
    stack = [(obj, 0)]
    while stack:
        cur, depth = stack.pop()
        if depth > max_depth:
            continue
        if isinstance(cur, dict):
            for k, v in cur.items():
                if k in target_keys:
                    return v
            for v in cur.values():
                stack.append((v, depth + 1))
        elif isinstance(cur, list):
            for v in cur:
                stack.append((v, depth + 1))
    return None


def _search_for_dicts_with_keys(obj, required_keys, max_depth=25):
    """
    Like _search_for_key() above, but returns EVERY dict containing all of
    `required_keys` instead of just the first value for one key - used by
    find_fotmob_match_url() below, which needs the whole list of that day's
    fixtures, not a single value.
    """
    found = []
    stack = [(obj, 0)]
    while stack:
        cur, depth = stack.pop()
        if depth > max_depth:
            continue
        if isinstance(cur, dict):
            if required_keys.issubset(cur.keys()):
                found.append(cur)
            for v in cur.values():
                stack.append((v, depth + 1))
        elif isinstance(cur, list):
            for v in cur:
                stack.append((v, depth + 1))
    return found


def find_fotmob_match_url(date_str, home_name, away_name):
    """
    Best-effort matcher for the batch runner: loads FotMob's day-schedule
    page for `date_str` (YYYY-MM-DD) and looks for a fixture whose team
    names match `home_name`/`away_name` (via combined_report's
    canonical_team_name(), so 'Man Utd' vs 'Manchester United', 'Spurs' vs
    'Tottenham Hotspur', etc. still match across the two sites' different
    naming), returning a FotMob match URL for it, or None if no match was
    found.

    HONESTY NOTE - READ BEFORE RELYING ON THIS: unlike _extract_via_network_
    logs() above (built and confirmed against a real captured 'matchdetails'
    response), the response this function looks for (anything with 'match'
    in its URL, containing dicts with 'home'/'away' keys) is an educated
    guess at FotMob's day-schedule API shape, not a verified one - there was
    no way to open a browser and inspect the real page/response from the
    environment this was written in. If this returns None for a match you
    know exists on FotMob, that's expected first-try friction for an
    unverified scraper - paste the FotMob URL manually instead (the batch
    runner UI always supports this), and share the day-schedule page's
    captured network responses so this can be corrected against real data,
    the same way every other WhoScored/FotMob schema surprise in this
    project got fixed.

    A local import of combined_report is used here (rather than importing
    it at module level) specifically so fotmob_report.py stays independently
    usable on its own (as fotmob_streamlit_app.py already relies on) for
    everyone NOT using the batch runner - this is the only function in this
    file that needs cross-source team-name matching at all.
    """
    from combined_report import canonical_team_name

    target_home = canonical_team_name(home_name)
    target_away = canonical_team_name(away_name)
    day_url = f"https://www.fotmob.com/matches?date={date_str.replace('-', '')}"

    print(f"Opening {day_url} ...")
    with get_driver(track_network=True) as driver:
        driver.get(day_url)
        WebDriverWait(driver, PAGE_LOAD_WAIT_SEC).until(
            EC.presence_of_element_located((By.TAG_NAME, 'body'))
        )
        time.sleep(HYDRATION_POLL_INTERVAL_SEC * 4)

        try:
            logs = driver.get_log('performance')
        except Exception as e:
            raise RuntimeError(
                f"Couldn't read performance logs (was track_network=True used?): {e}"
            )

    fixture_dicts = []
    for entry in logs:
        try:
            message = json.loads(entry['message'])['message']
        except (KeyError, json.JSONDecodeError, TypeError):
            continue
        if message.get('method') != 'Network.responseReceived':
            continue
        params = message.get('params', {})
        resp_url = params.get('response', {}).get('url', '')
        if 'match' not in resp_url.lower():
            continue
        request_id = params.get('requestId')
        try:
            body = driver.execute_cdp_cmd('Network.getResponseBody', {'requestId': request_id})
        except Exception:
            continue
        text = body.get('body', '')
        if body.get('base64Encoded'):
            try:
                text = base64.b64decode(text).decode('utf-8', errors='replace')
            except Exception:
                continue
        try:
            data = json.loads(text)
        except json.JSONDecodeError:
            continue
        fixture_dicts.extend(_search_for_dicts_with_keys(data, {'home', 'away'}))

    print(f"Day-schedule scan: found {len(fixture_dicts)} fixture-like object(s) for {date_str}.")

    for fixture in fixture_dicts:
        home = fixture.get('home')
        away = fixture.get('away')
        h_name = home.get('name') if isinstance(home, dict) else None
        a_name = away.get('name') if isinstance(away, dict) else None
        if not h_name or not a_name:
            continue
        if canonical_team_name(h_name) != target_home or canonical_team_name(a_name) != target_away:
            continue
        match_id = (fixture.get('id') or fixture.get('matchId')
                    or (home.get('id') if isinstance(home, dict) else None))
        if not match_id:
            continue
        slug_home = re.sub(r'[^a-z0-9]+', '-', h_name.lower()).strip('-')
        slug_away = re.sub(r'[^a-z0-9]+', '-', a_name.lower()).strip('-')
        return f"https://www.fotmob.com/matches/{slug_home}-vs-{slug_away}#{match_id}"

    return None


def _get_first(d, keys, default=None):
    """Return the first present, non-None value among several candidate keys."""
    if not isinstance(d, dict):
        return default
    for k in keys:
        if k in d and d[k] is not None:
            return d[k]
    return default


def _shots_list(match_json):
    """Return the actual shots list (possibly empty) found in a match_json blob, or None."""
    shots = _search_for_key(match_json, {'shots'})
    if not shots:
        shotmap = _search_for_key(match_json, {'shotmap'})
        shots = shotmap.get('shots') if isinstance(shotmap, dict) else None
    return shots


def _matches_target_id(match_json, match_id):
    """
    Check whether the matchId embedded IN the JSON payload itself matches the
    matchId we parsed from the URL. This matters because FotMob's server-side
    render for a given slug/shortcode can default to a DIFFERENT match than
    the one named in the URL's '#<matchId>' fragment (fragments are never
    sent to a server at all - they're purely client-side) - e.g. a slug
    shared by a team pair can default-render "whichever meeting is next"
    rather than the specific historical match the fragment points to.
    """
    found_id = _search_for_key(match_json, {'matchId'})
    return found_id is not None and str(found_id) == str(match_id)


def _extract_content_json(next_data):
    """
    Pull the actual match-content dict out of a parsed __NEXT_DATA__ blob.
    Handles both the "populated" shape (props.pageProps.content.{shotmap,
    stats,...}) and the "deferred" shape ({'fetchingLeagueData': True, ...},
    no content yet - see ANTI-SCRAPING NOTE in the module docstring).
    """
    if not next_data:
        return None
    candidate = _search_for_key(next_data, {'content'})
    if isinstance(candidate, dict) and (candidate.get('shotmap') or candidate.get('stats')):
        return candidate
    # Some pages nest shotmap/stats directly rather than under a 'content' key.
    shotmap = _search_for_key(next_data, {'shotmap'})
    if shotmap:
        return next_data
    return None


def _extract_via_network_logs(driver, match_id):
    """
    Read Chrome's captured network traffic (via CDP performance logs, which
    requires the driver to have been created with track_network=True) and
    find FotMob's OWN matchDetails response - the one the page's real,
    fully-hydrated JS made, with a correctly-generated x-mas header. This
    sidesteps needing to fake that header entirely: we're just reading a
    response FotMob's own app already legitimately received.

    Returns the parsed JSON body of the response whose matchId matches
    `match_id`, or None if no such response was captured.
    """
    try:
        logs = driver.get_log('performance')
    except Exception as e:
        print(f"Couldn't read performance logs (was track_network=True used?): {e}")
        return None

    candidates = []  # (requestId, url)
    for entry in logs:
        try:
            message = json.loads(entry['message'])['message']
        except (KeyError, json.JSONDecodeError, TypeError):
            continue
        if message.get('method') != 'Network.responseReceived':
            continue
        params = message.get('params', {})
        resp_url = params.get('response', {}).get('url', '')
        if 'matchdetails' in resp_url.lower():
            candidates.append((params.get('requestId'), resp_url))

    print(f"Network logs: found {len(candidates)} matchDetails-like response(s).")
    best = None
    for request_id, resp_url in candidates:
        try:
            body = driver.execute_cdp_cmd('Network.getResponseBody', {'requestId': request_id})
        except Exception as e:
            print(f"  {resp_url}: couldn't fetch response body ({e})")
            continue
        text = body.get('body', '')
        if body.get('base64Encoded'):
            try:
                text = base64.b64decode(text).decode('utf-8', errors='replace')
            except Exception as e:
                print(f"  {resp_url}: couldn't base64-decode body ({e})")
                continue
        try:
            data = json.loads(text)
        except json.JSONDecodeError:
            print(f"  {resp_url}: response body wasn't valid JSON")
            continue
        found_id = _search_for_key(data, {'matchId'})
        found_shots = len(_shots_list(data) or [])
        print(f"  {resp_url} -> matchId={found_id}, shots={found_shots}")
        if str(found_id) == str(match_id):
            return data
        best = best or data  # remember a fallback in case none match exactly
    return best


def scrape_match(url: str, out_dir: str = '.'):
    """
    Loads the FotMob match page in a real (non-headless, network-logging)
    browser and returns the parsed match-content dict plus the matchId.
    Always writes the raw JSON to fotmob_raw_<matchId>.json in out_dir for
    debugging - see the DEBUGGING NOTE in the module docstring.

    Primary method: read the actual matchDetails network response FotMob's
    own page JS received (via _extract_via_network_logs) - this is the only
    approach confirmed to reliably get the RIGHT match's data, since it's a
    genuine response with a correctly-generated x-mas header, not something
    we're trying to reconstruct ourselves. Requires get_driver(track_network=
    True) so Chrome's performance/network logging is enabled AND so a real
    (non-headless) browser actually runs the page's JS - see ANTI-SCRAPING
    NOTE for why headless/JS-disabled sessions can silently show the wrong
    match with no error at all.

    Falls back to polling the page's embedded __NEXT_DATA__ JSON if no
    matching network response was captured (e.g. a pre-rendered match that
    never needed a client-side fetch at all).
    """
    match_id = extract_match_id(url)
    match_json = None
    with get_driver(track_network=True) as driver:
        driver.get(url)
        WebDriverWait(driver, PAGE_LOAD_WAIT_SEC).until(
            EC.presence_of_element_located((By.TAG_NAME, 'body'))
        )
        # Give the page's own JS time to hydrate and make its real request.
        time.sleep(HYDRATION_POLL_INTERVAL_SEC * 4)

        match_json = _extract_via_network_logs(driver, match_id)

        if match_json is None or not _matches_target_id(match_json, match_id):
            print("Network-log extraction didn't find the target match - "
                  "falling back to polling embedded page JSON.")
            for attempt in range(1, HYDRATION_POLL_ATTEMPTS + 1):
                html = driver.page_source
                next_data = _find_next_data_json(html)
                candidate = _extract_content_json(next_data)

                found_id = _search_for_key(candidate, {'matchId'}) if candidate else None
                found_shots = len(_shots_list(candidate) or []) if candidate else 0
                print(f"Hydration poll {attempt}/{HYDRATION_POLL_ATTEMPTS}: "
                      f"found matchId={found_id}, shots={found_shots}, target matchId={match_id}")

                if candidate and (match_json is None or found_shots):
                    match_json = candidate
                if candidate and found_shots and _matches_target_id(candidate, match_id):
                    break
                if attempt < HYDRATION_POLL_ATTEMPTS:
                    time.sleep(HYDRATION_POLL_INTERVAL_SEC)

    if match_json is None:
        raise RuntimeError(
            "Couldn't find match data via either the embedded page JSON or a "
            "browser-side fetch. FotMob likely changed something - re-inspect "
            "the page's Network tab for the matchDetails request and compare "
            "against the DEBUGGING NOTE in this file's module docstring."
        )

    if not _matches_target_id(match_json, match_id):
        print(f"WARNING: final match_json's own matchId doesn't match the target ({match_id}) - "
              "this report is very likely describing the WRONG match. See the fetch debug output "
              "above for why the explicit-matchId fetch didn't take over.")

    os.makedirs(out_dir, exist_ok=True)
    raw_path = os.path.join(out_dir, f'fotmob_raw_{match_id}.json')
    with open(raw_path, 'w') as f:
        json.dump(match_json, f, indent=2)
    print(f"Wrote raw matchDetails JSON to {raw_path} (for debugging).")

    return match_json, match_id



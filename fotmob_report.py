def compute_shots(match_json):
    """One row per shot, across both teams, sorted chronologically."""
    shots = _search_for_key(match_json, {'shots'})
    if not shots:
        shotmap = _search_for_key(match_json, {'shotmap'})
        shots = shotmap.get('shots') if isinstance(shotmap, dict) else None

    columns = ['Team', 'Player', 'Minute', 'Added Time', 'Period', 'Situation',
               'Body Part', 'Outcome', 'On Target', 'xG', 'xGOT', 'X', 'Y']
    if not shots:
        return pd.DataFrame(columns=columns)

    team_map = extract_team_id_map(match_json)

    rows = []
    for s in shots:
        team_id = _get_first(s, ['teamId'])
        team_name = team_map.get(team_id, str(team_id))
        event_type = _get_first(s, ['eventType'])
        outcome = OUTCOME_MAP.get(event_type, event_type)
        body_part_raw = _get_first(s, ['shotType'])
        body_part = BODY_PART_MAP.get(body_part_raw, body_part_raw)
        on_target_flag = _get_first(s, ['isOnTarget'])
        on_target = bool(on_target_flag) if on_target_flag is not None else outcome in {'Goal', 'Saved'}
        rows.append({
            'Team': team_name,
            'Player': _get_first(s, ['playerName', 'name']),
            'Minute': _get_first(s, ['min', 'minute']),
            'Added Time': _get_first(s, ['minAdded', 'minuteAdded'], 0),
            'Period': _get_first(s, ['period']),
            'Situation': _get_first(s, ['situation']),
            'Body Part': body_part,
            'Outcome': outcome,
            'On Target': on_target,
            'xG': _get_first(s, ['expectedGoals', 'xg', 'xG']),
            'xGOT': _get_first(s, ['expectedGoalsOnTarget', 'xgot', 'xGOT']),
            'X': _get_first(s, ['x']),
            'Y': _get_first(s, ['y']),
        })

    df = pd.DataFrame(rows, columns=columns)
    sort_cols = [c for c in ['Minute', 'Added Time'] if c in df.columns]
    if sort_cols:
        df = df.sort_values(sort_cols, na_position='last').reset_index(drop=True)
    return df



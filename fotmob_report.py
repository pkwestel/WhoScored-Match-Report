def extract_player_windows(match_json, player_minutes=None, shots_df=None):
    """
    Per-player on-pitch window for this match: Team, Player, start_minute,
    end_minute, Minutes Played, subbed_off. Backs the Plus Minus tab (see
    compute_plus_minus() below) - it's the "which minutes was this player
    actually on the pitch for" data that FotMob's shot map alone can't
    answer.

    Read from FotMob's own lineup data (content.lineup.homeTeam/awayTeam,
    each with 'starters' + 'subs' lists). Each player's own
    'performance.substitutionEvents' list carries a 'subIn' and/or 'subOut'
    entry with its own 'time' (in minutes) when applicable.

    start_minute is that player's 'subIn' time if they came on as a
    substitute, else 0 (they started the match). end_minute is their
    'subOut' time if they were substituted off - this case needs nothing
    else, since sub_in/sub_out times alone fully define their window.
    Otherwise (played to the final whistle - a starter never subbed off,
    or a substitute who stayed on) end_minute is start_minute + however
    many minutes they're known to have played: preferably FotMob's own
    per-player Minutes Played figure (from extract_player_minutes, passed
    in via player_minutes or computed here if not given) since that
    already correctly accounts for stoppage time; but FotMob's per-player
    stats (unlike the shot map) are sometimes missing or incomplete, most
    often for a very recently finished match FotMob hasn't fully processed
    yet - when that per-player figure isn't available for a player who
    otherwise clearly appeared (has a lineup rating, or a sub event),
    end_minute falls back to a match-wide estimate instead: the latest
    effective minute (Minute + Added Time) seen anywhere on the shot map
    (passed in via shots_df), or a flat 90 if there's no shot map either.
    That fallback is necessarily an approximation - it can't know about
    stoppage time beyond whatever the shot map itself shows - which is
    why FotMob's own figure is always preferred when it's there.

    subbed_off (bool) tells compute_plus_minus() how to treat the boundary
    at end_minute: a player who WAS subbed off doesn't get credit for the
    exact minute they left (that minute belongs to whoever replaced them),
    while a player who finished the match does get credit for the final
    minute itself (so a stoppage-time shot at the very end still counts
    for them).

    Bench players who never actually appeared (no lineup rating, no sub
    event, and no resolvable Minutes Played figure) are skipped entirely -
    there's no on-pitch window to give them. If FotMob returns no lineup
    detail at all for this match (a bare team name/id with no starters/
    subs lists - this does happen, most often for a match FotMob hasn't
    finished processing), this returns an empty DataFrame; there is
    nothing to fall back to in that case since there's no per-player data
    of any kind to start from.
    """
    columns = ['Team', 'Player', 'start_minute', 'end_minute', 'Minutes Played', 'subbed_off']
    lineup = match_json.get('lineup') if isinstance(match_json, dict) else None
    if not isinstance(lineup, dict):
        # Some responses nest lineup under a 'content' key instead of
        # carrying it top-level (same shape variance _shots_list/
        # extract_player_xa already handle) - fall back to a full search
        # before concluding there's really no lineup data at all.
        lineup = _search_for_key(match_json, {'lineup'})
    if not isinstance(lineup, dict):
        return pd.DataFrame(columns=columns)

    if player_minutes is None:
        player_minutes = extract_player_minutes(match_json)
    minutes_lookup = {(r['Team'], r['Player']): r['Minutes Played'] for _, r in player_minutes.iterrows()}

    fallback_end = 90.0
    if shots_df is not None and not shots_df.empty:
        eff = shots_df['Minute'].fillna(0) + shots_df['Added Time'].fillna(0)
        if len(eff):
            fallback_end = max(fallback_end, eff.max())

    rows = []
    for side_key in ('homeTeam', 'awayTeam'):
        side = lineup.get(side_key)
        if not isinstance(side, dict):
            continue
        team_name = side.get('name')
        players = (side.get('starters') or []) + (side.get('subs') or [])
        for p in players:
            if not isinstance(p, dict):
                continue
            name = p.get('name')
            perf = p.get('performance') or {}
            sub_events = perf.get('substitutionEvents') or []
            sub_in = next((e.get('time') for e in sub_events if e.get('type') == 'subIn'), None)
            sub_out = next((e.get('time') for e in sub_events if e.get('type') == 'subOut'), None)
            rating = perf.get('rating')
            minutes_played = minutes_lookup.get((team_name, name))

            appeared = minutes_played is not None or sub_in is not None or sub_out is not None or rating is not None
            if not appeared:
                continue  # never actually appeared (unused bench player)

            start = sub_in if sub_in is not None else 0
            subbed_off = sub_out is not None
            if subbed_off:
                end = sub_out
            elif minutes_played is not None:
                end = start + minutes_played
            else:
                end = fallback_end  # FotMob's own per-player total wasn't available - best effort

            rows.append({
                'Team': team_name, 'Player': name,
                'start_minute': start, 'end_minute': end,
                'Minutes Played': round(minutes_played) if minutes_played is not None else round(end - start),
                'subbed_off': subbed_off,
            })

    return pd.DataFrame(rows, columns=columns)


def compute_plus_minus(shots_df, player_windows, home_name=None, away_name=None):
    """
    Plus Minus tab: for every player, totals of Goals For/Against, Shots
    For/Against, and xG For/Against for exactly the minutes they were on
    the pitch (their window from extract_player_windows() above) - the
    shot/goal/xG state that existed specifically while that player was out
    there, not the match's grand total. E.g. if a player is subbed off
    having played 70 minutes, their row shows the totals through that 70th
    minute; whoever replaces them shows the totals for the remaining
    minutes of the match.

    Penalties are excluded from every one of these six columns (Situation
    == 'Penalty') - the same treatment as the Shot Breakdown tab, and for
    the same reason: a penalty isn't a shot in the run-of-play sense.

    xG For/Against is NOT a simple sum of each shot's own xG value. Shots
    by the SAME team at the exact same effective minute (Minute + Added
    Time) are treated as one sequence - almost certainly a rebound/scramble
    in the same phase of play, since FotMob's shot map carries no separate
    possession/sequence ID to group on more precisely - and combined into a
    single probability (1 minus the product of (1 - xG) across that
    sequence's shots) rather than added together, since simply summing
    individual shot xG values overstates the true combined chance of
    scoring from one spell of play. Shots in different minutes are treated
    as independent and their (already sequence-combined) values are simply
    added together as usual.

    Returns one DataFrame with a Team column - split into two tables, one
    per team, when written to the workbook/UI (see build_workbook()).
    Columns: Team, Player, Minutes Played, Goals For, Goals Against, Shots,
    Shots Against, xG, xG Against.
    """
    out_cols = ['Team', 'Player', 'Minutes Played', 'Goals For', 'Goals Against',
                'Shots', 'Shots Against', 'xG', 'xG Against']
    if shots_df.empty or player_windows.empty:
        return pd.DataFrame(columns=out_cols)

    work = shots_df[shots_df['Situation'] != 'Penalty'].copy()
    work['xG'] = work['xG'].fillna(0.0)
    work['Minute'] = work['Minute'].fillna(0)
    work['Added Time'] = work['Added Time'].fillna(0)
    work['_effective_minute'] = work['Minute'] + work['Added Time']

    # Sequence-combine xG: shots by the same team at the exact same
    # effective minute become one combined probability, not a plain sum.
    seq = (work.groupby(['Team', '_effective_minute'])['xG']
           .apply(lambda xs: 1 - (1 - xs).prod())
           .reset_index(name='seq_xG'))

    teams_all = ([t for t in [home_name, away_name] if t is not None]
                 or sorted(player_windows['Team'].dropna().unique()))
    opponent = {teams_all[0]: teams_all[1], teams_all[1]: teams_all[0]} if len(teams_all) == 2 else {}

    records = []
    for _, prow in player_windows.iterrows():
        team = prow['Team']
        opp = opponent.get(team)
        start, end, subbed_off = prow['start_minute'], prow['end_minute'], prow['subbed_off']

        if subbed_off:
            mask = lambda m: (m >= start) & (m < end)
        else:
            mask = lambda m: (m >= start) & (m <= end)

        own_shots = work[(work['Team'] == team) & mask(work['_effective_minute'])]
        opp_shots = work[(work['Team'] == opp) & mask(work['_effective_minute'])] if opp else work.iloc[0:0]
        own_seq = seq[(seq['Team'] == team) & mask(seq['_effective_minute'])]
        opp_seq = seq[(seq['Team'] == opp) & mask(seq['_effective_minute'])] if opp else seq.iloc[0:0]

        records.append({
            'Team': team,
            'Player': prow['Player'],
            'Minutes Played': prow['Minutes Played'],
            'Goals For': int((own_shots['Outcome'] == 'Goal').sum()),
            'Goals Against': int((opp_shots['Outcome'] == 'Goal').sum()),
            'Shots': int(len(own_shots)),
            'Shots Against': int(len(opp_shots)),
            'xG': round(own_seq['seq_xG'].sum(), 2),
            'xG Against': round(opp_seq['seq_xG'].sum(), 2),
        })

    out = pd.DataFrame(records, columns=out_cols)
    out = out.sort_values(['Team', 'Minutes Played'], ascending=[True, False]).reset_index(drop=True)
    return out


def compute_shot_breakdowns(shots_df, player_xa=None, player_minutes=None):
    """
    Roll the shot map up along a few dimensions - by player, by situation
    (open play / set piece / penalty / corner / fast break, per FotMob's own
    'situation' field), and by body part - each broken out per team. Every
    breakdown uses the same Shots / Goals / Total xG columns as the Totals
    tab (minus Shots on Target - not carried on this tab), just at a finer
    grain. If player_xa (from extract_player_xa) is supplied, an extra xA
    column is merged onto the 'By Player' table only - it's a per-player
    stat, not something the other two dimensions (situation/body part) can
    meaningfully carry. Likewise, if player_minutes (from
    extract_player_minutes) is supplied, a Minutes Played column is merged
    onto the 'By Player' table only, placed directly to the right of Player
    (before Shots).

    Penalties are excluded from Shots / Goals / Total xG everywhere on this
    tab - a penalty kick isn't a shot in the run-of-play sense, so it
    shouldn't inflate a player's/team's shot volume, expected goals, or
    actual goals tally. A group's Total xG is computed as that group's full
    xG total (every shot, penalties included) minus PENALTY_XG (FotMob's own
    flat 0.79 expected-goals value for any penalty) times however many
    penalties are in that group - rather than simply summing only the
    non-penalty shots' own xG figures - so the result doesn't depend on
    whatever value the shot map's own xG field happens to carry for a
    penalty. A group made up entirely of penalties (most notably the
    'Penalty' row that would otherwise appear on the By Situation table)
    drops out of its breakdown entirely, since after this exclusion it would
    only ever show up as an all-zero row.

    Any player with xA > 0 is included on the 'By Player' table even if they
    took zero (non-penalty) shots (e.g. a player who set up a good chance but
    didn't shoot themselves) - their Shots/Goals/Total xG all show 0 in that
    case.

    Returns an ordered dict: {'By Player': df, 'By Situation': df, 'By Body
    Part': df}, each sorted by team then descending shot count.
    """
    breakdowns = {}
    for label, group_col in SHOT_BREAKDOWN_DIMENSIONS:
        cols = ['Team', group_col, 'Shots', 'Goals', 'Total xG']
        if label == 'By Player':
            out_cols = ['Team', group_col, 'Minutes Played', 'Shots', 'Goals', 'Total xG', 'xA']
        else:
            out_cols = cols
        if shots_df.empty or group_col not in shots_df.columns:
            agg = pd.DataFrame(columns=cols)
        else:
            work = shots_df.dropna(subset=[group_col]).copy()
            if work.empty:
                agg = pd.DataFrame(columns=cols)
            else:
                work['xG'] = work['xG'].fillna(0.0)
                is_pen = work['Situation'] == 'Penalty'
                non_pen = work[~is_pen]

                if non_pen.empty:
                    agg = pd.DataFrame(columns=cols)
                else:
                    group_keys = ['Team', group_col]
                    total_xg_all = work.groupby(group_keys)['xG'].sum()
                    pen_counts = is_pen.groupby([work['Team'], work[group_col]]).sum()

                    agg = non_pen.groupby(group_keys).agg(
                        Shots=('Outcome', 'size'),
                        Goals=('Outcome', lambda s: int((s == 'Goal').sum())),
                    ).reset_index()
                    agg = agg.set_index(group_keys)
                    non_pen_xg = (total_xg_all.reindex(agg.index).fillna(0.0)
                                  - PENALTY_XG * pen_counts.reindex(agg.index).fillna(0))
                    agg['Total xG'] = non_pen_xg.clip(lower=0).round(2)
                    agg = agg.reset_index()
                    agg = agg[cols]

        if label == 'By Player':
            if player_xa is not None and not player_xa.empty:
                agg = agg.merge(player_xa, how='left', on=['Team', 'Player'])
            else:
                agg['xA'] = 0.0
            agg['xA'] = agg['xA'].fillna(0.0).round(2)

            if player_minutes is not None and not player_minutes.empty:
                agg = agg.merge(player_minutes, how='left', on=['Team', 'Player'])
            else:
                agg['Minutes Played'] = None

            # Add zero-shot rows for any player with xA > 0 who isn't already
            # in the table (took no shots themselves, but created a chance).
            if player_xa is not None and not player_xa.empty:
                existing = set(zip(agg['Team'], agg['Player']))
                extra = player_xa[
                    (player_xa['xA'] > 0)
                    & ~player_xa.apply(lambda r: (r['Team'], r['Player']) in existing, axis=1)
                ].copy()
                if not extra.empty:
                    extra['Shots'] = 0
                    extra['Goals'] = 0
                    extra['Total xG'] = 0.0
                    extra['xA'] = extra['xA'].round(2)
                    if player_minutes is not None and not player_minutes.empty:
                        extra = extra.merge(player_minutes, how='left', on=['Team', 'Player'])
                    else:
                        extra['Minutes Played'] = None
                    agg = pd.concat([agg, extra[out_cols]], ignore_index=True)

        agg = agg.sort_values(['Team', 'Shots'], ascending=[True, False]).reset_index(drop=True)
        breakdowns[label] = agg[out_cols]
    return breakdowns


# ============================================================
# 5c. xG BREAKDOWN (by half, by phase) - second table on the Totals tab
# ============================================================
# FotMob's shot "situation" values that count as a set piece (a stopped-ball
# restart) - anything else (RegularPlay, FastBreak, etc.) counts as Open Play.
SET_PIECE_SITUATIONS = {'SetPiece', 'FromCorner', 'Penalty'}
# Extra-time periods get lumped into "2nd Half" rather than dropped, since
# most matches never reach extra time and dropping them silently would be
# worse than this simplification for the rare cup match that does.
SECOND_HALF_PERIODS = {'SecondHalf', 'FirstExtraHalf', 'SecondExtraHalf'}


def compute_xg_breakdown(shots_df, home_name, away_name):
    """
    Team-level shots and xG split two different ways: by half (1st/2nd, from
    FotMob's 'period' field) and by phase (Open Play vs Set Piece, from
    FotMob's 'situation' field - see SET_PIECE_SITUATIONS above for exactly
    which situations count as a set piece). The half columns (shots and xG)
    and the phase columns (xG only) are independent cuts of the same shot
    map, not mutually exclusive categories of each other - e.g. a set piece
    goal in the 2nd half adds to both '2nd Half xG' and 'Set Piece xG'.
    """
    teams_order = [t for t in [home_name, away_name] if t] or sorted(shots_df['Team'].dropna().unique())
    count_cols = ['1st Half Shots', '2nd Half Shots']
    xg_cols = ['1st Half xG', '2nd Half xG', 'Open Play xG', 'Set Piece xG']
    cols = count_cols + xg_cols
    out = pd.DataFrame({'team': teams_order}).set_index('team')
    for c in count_cols:
        out[c] = 0
    for c in xg_cols:
        out[c] = 0.0

    if not shots_df.empty:
        work = shots_df.copy()
        work['xG'] = work['xG'].fillna(0.0)

        first_half_mask = work['Period'] == 'FirstHalf'
        second_half_mask = work['Period'].isin(SECOND_HALF_PERIODS)
        is_set_piece = work['Situation'].isin(SET_PIECE_SITUATIONS)

        first_half_shots = work[first_half_mask].groupby('Team').size()
        second_half_shots = work[second_half_mask].groupby('Team').size()
        first_half_xg = work[first_half_mask].groupby('Team')['xG'].sum()
        second_half_xg = work[second_half_mask].groupby('Team')['xG'].sum()
        set_piece_xg = work[is_set_piece].groupby('Team')['xG'].sum()
        open_play_xg = work[~is_set_piece].groupby('Team')['xG'].sum()

        for col, series in [('1st Half Shots', first_half_shots), ('2nd Half Shots', second_half_shots)]:
            out[col] = series.reindex(out.index).fillna(0).astype(int)
        for col, series in [('1st Half xG', first_half_xg), ('2nd Half xG', second_half_xg),
                             ('Open Play xG', open_play_xg), ('Set Piece xG', set_piece_xg)]:
            out[col] = series.reindex(out.index).fillna(0.0)

    for c in xg_cols:
        out[c] = out[c].round(2)
    out = out.reindex(teams_order).reset_index()
    return out



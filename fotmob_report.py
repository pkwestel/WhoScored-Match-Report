def sanitize_filename(name):
    return re.sub(r'[^A-Za-z0-9]+', '', name) if name else 'Unknown'


def main():
    parser = argparse.ArgumentParser(description='Generate a FotMob match shots/xG report.')
    parser.add_argument('url', help='FotMob match URL, e.g. https://www.fotmob.com/matches/<slug>/<code>#<matchId>')
    parser.add_argument('--out-dir', default='.', help='Directory to save the workbook + raw JSON debug dump in.')
    args = parser.parse_args()

    print(f"Scraping {args.url} ...")
    match_json, match_id = scrape_match(args.url, out_dir=args.out_dir)

    home_name, away_name = extract_team_names(match_json)
    print(f"Match {match_id}: {home_name} vs {away_name}")

    print("Computing shots...")
    shots_df = compute_shots(match_json)
    print(f"Found {len(shots_df)} shots.")
    if shots_df.empty:
        hint = extract_match_status_hint(match_json)
        if hint:
            print(f"No shots found - likely reason: {hint}")
        else:
            print("No shots found and no status hint available - check the raw JSON dump.")

    print("Computing totals...")
    totals_df = compute_totals(match_json, shots_df, home_name, away_name)

    print("Computing shot breakdowns...")
    player_xa = extract_player_xa(match_json)
    shot_breakdowns = compute_shot_breakdowns(shots_df, player_xa)

    print("Computing xG breakdown...")
    xg_breakdown = compute_xg_breakdown(shots_df, home_name, away_name)

    print("Building workbook...")
    wb = build_workbook(shots_df, totals_df, home_name, away_name, match_id, shot_breakdowns, xg_breakdown)

    filename = f"{sanitize_filename(home_name)}_vs_{sanitize_filename(away_name)}_fotmob.xlsx"
    out_path = os.path.join(args.out_dir, filename)
    wb.save(out_path)
    print(f"Saved: {out_path}")


if __name__ == '__main__':
    main()

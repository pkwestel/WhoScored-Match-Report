"""
FotMob Match Report Generator
==============================

Scrapes a FotMob match page and builds an Excel workbook with:
  - Shots: one row per shot (the "shot map") - player, minute, situation,
    body part, outcome, xG, xGOT, and pitch coordinates as FotMob reports
    them.
  - Shot Breakdown: the Shots tab rolled up per team along three
    dimensions - by player, by situation (open play/set piece/penalty/
    corner/fast break), and by body part.
  - Totals: team-level numbers rolled up from the shot map (Shots, Shots
    on Target, Goals, Total xG) plus whatever aggregated match stats
    FotMob itself publishes for the match (possession, corners, fouls,
    cards, passes, etc. - whichever stat groups FotMob includes for a
    given match). A second table below it splits xG by half and by
    phase (Open Play vs Set Piece).
  - Plus Minus: one table per team, one row per player, showing Goals
    For/Against, Shots For/Against, and xG For/Against for exactly the
    minutes that player was on the pitch (from FotMob's own lineup/
    substitution data - see extract_player_windows() and
    compute_plus_minus()). Penalties are excluded, and xG is combined
    per-sequence (same-team shots at the same minute) rather than simply
    summed.
  - Notes: definitions/assumptions, kept in sync with this docstring.

WHY THIS LOOKS DIFFERENT FROM whoscored_report.py
--------------------------------------------------
WhoScored/Opta exposes a full event-by-event log (every pass, tackle,
touch, each with x/y coordinates), which is what let the WhoScored report
build Touches/Passing/Defensive-Actions tabs - full possession
reconstruction. FotMob's match data is NOT a full event log. It's a shot
map (every shot, with xG/xGOT) plus a set of aggregated team/player
stats that FotMob itself computes. That's a narrower, differently-shaped
dataset, so this report is scoped to shots/xG plus FotMob's own
aggregate stats, rather than trying to recreate the WhoScored tab set on
data that doesn't exist in that shape here.

SETUP (same pattern as whoscored_report.py)
--------------------------------------------
Requires Selenium + a real Chrome browser via the same utils/driver.py
helper (get_driver()) already used by whoscored_report.py, plus:
    pip install selenium beautifulsoup4 pandas openpyxl

IMPORTANT: this script calls get_driver(track_network=True), not the
plain get_driver() whoscored_report.py uses. That mode (a) runs a real,
VISIBLE (non-headless) Chrome window rather than headless, and (b)
enables Chrome's network/performance logging - both are required for
the network-log capture described below. Expect an actual browser
window to pop up while this runs; that's intentional.

Usage:
    python fotmob_report.py "https://www.fotmob.com/matches/<slug>/<code>#<matchId>"

ANTI-SCRAPING NOTE (important - confirmed by live testing, not just theory)
-----------------------------------------------------------------------------
FotMob's real API host is `apigw.fotmob.com` (the old `www.fotmob.com/api/*`
paths are gone entirely and 404). Calling `apigw.fotmob.com/matchDetails`
directly - with `requests`, or even with `fetch()` executed inside the
browser's own JS context via Selenium - reliably 404s, because the
`x-mas` auth header it requires is generated by FotMob's obfuscated
client bundle through some internal signing path, not just "any fetch
call from the page". Confirmed dead (404, not 401) in practice - don't
waste time re-attempting a direct fetch.

Reading the page's embedded Next.js JSON (a <script id="__NEXT_DATA__">
tag) was tried next and ALSO confirmed unreliable for this project's
actual use case: FotMob's short "team-vs-team" URLs (the
`/matches/<slug>/<shortcode>#<matchId>` form) can have their shortcode
alone default-render whichever meeting between two teams is
chronologically NEXT, ignoring the `#<matchId>` fragment (fragments are
never sent to a server - only client-side JS can act on them). Crucially,
__NEXT_DATA__ is a static, server-render-time snapshot; even once a real
user's browser corrects itself client-side and shows the right match on
screen, that script tag does NOT get rewritten to match - so polling it,
however long, keeps reading the same wrong snapshot. Confirmed by live
testing: 10 polls over 15 seconds, zero change.

The approach that actually works: capture the REAL matchDetails network
response FotMob's own page JS receives once it corrects itself (a
genuine response, with a correctly-generated x-mas header, since it's
FotMob's own code making that request - we're just reading it, not
forging it). This requires Chrome's CDP performance/network logging
(get_driver(track_network=True) already sets the right capability) and
a non-headless session actually running FotMob's real client JS - a
headless session, or one with JavaScript disabled entirely, may never
even MAKE that corrected request, let alone let us observe it. See
_extract_via_network_logs(). Embedded __NEXT_DATA__ polling is kept as a
fallback for the (probably common) case of a pre-rendered, popular match
that never needed a corrective client-side fetch at all.

A second wrinkle, specific to FotMob's short "team-vs-team" URLs (the
`/matches/<slug>/<shortcode>#<matchId>` form): the shortcode alone can
default-render whichever meeting between two teams is chronologically
NEXT, ignoring the `#<matchId>` fragment (fragments are never sent to a
server at all - only client-side JS can act on them). A real browser's
own JS does read that fragment and correct itself, but that correction
also happens as part of the same client-side hydration process, which is
exactly why the polling above matters for BOTH problems at once - see
_matches_target_id(), which is used throughout to confirm the JSON we
finally have is for the actual matchId the URL named, not "whatever
loaded first."

DEBUGGING NOTE
---------------
FotMob's internal JSON schema isn't publicly documented and has already
changed at least once (the 2024 header/host change). Because of that,
this script always writes the raw JSON it ended up using to
fotmob_raw_<matchId>.json next to wherever the workbook is saved, and
prints diagnostics about what it found at each polling attempt. If a run
produces an empty/wrong-looking report, that console output plus the raw
JSON file are the first things to check - a field-extraction helper
(`_get_first`, tries several candidate key names) is used throughout
specifically so small schema drifts don't silently break everything, but
a bigger schema change will need that raw JSON to diagnose.

NOTES / ASSUMPTIONS (kept in sync with the Notes tab)
-------------------------------------------------------
  - Outcome is normalized from FotMob's shot "eventType" field (Goal /
    AttemptSaved -> Saved / Miss -> Off Target / AttemptBlocked ->
    Blocked / Post -> Hit Post / OwnGoal).
  - Body Part is normalized from FotMob's shot "shotType" field.
  - On Target is FotMob's own isOnTarget flag where present, else
    inferred as True for Goal/Saved outcomes.
  - X/Y are left exactly as FotMob reports them (coordinate scale/
    orientation not independently verified yet - flagged for review
    once we see a real raw JSON dump).
  - Total xG per team is the sum of the shot map's xG values for that
    team - this should match (or come very close to) FotMob's own
    published xG stat for the match; worth spot-checking on first run.
  - Any stat FotMob doesn't publish for a given match (e.g. no
    Expected Goals group at lower-profile competitions) will just be
    absent as a column rather than erroring.
"""

